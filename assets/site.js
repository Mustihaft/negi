// Newest release from GitHub; the page already points at a working installer if this fails.
fetch('https://api.github.com/repos/Mustihaft/negi/releases/latest')
  .then((r) => (r.ok ? r.json() : Promise.reject(r.status)))
  .then((rel) => {
    const exe = rel.assets.find((a) => /\.exe$/i.test(a.name))
    const sha = exe && ((exe.digest || '').replace(/^sha256:/, '') || ((rel.body || '').match(/\b[a-f0-9]{64}\b/i) || [])[0])
    // Use the API only when every value looks exactly like this repository's installer: the
    // name and checksum end up in a command people paste into PowerShell. Otherwise the
    // built-in 0.1.7 link, version and checksum stay, together.
    const ours = (url, path) => typeof url === 'string' && url.startsWith(`https://github.com/Mustihaft/negi/releases/${path}/`)
    if (
      !exe || !/^[A-Za-z0-9._-]+\.exe$/.test(exe.name) || !/^[a-f0-9]{64}$/i.test(sha || '') ||
      !Number.isFinite(exe.size) || !ours(exe.browser_download_url, 'download') || !ours(rel.html_url, 'tag') ||
      !/^v?[0-9][0-9A-Za-z.-]*$/.test(rel.tag_name)
    )
      return
    const set = (sel, text) => document.querySelectorAll(sel).forEach((el) => (el.textContent = text))
    document.querySelectorAll('[data-dl]').forEach((a) => (a.href = exe.browser_download_url))
    document.querySelectorAll('[data-notes]').forEach((a) => (a.href = rel.html_url))
    set('[data-version]', rel.tag_name.replace(/^v/, ''))
    set('[data-size]', Math.round(exe.size / 1048576) + ' MB')
    set('[data-file]', exe.name)
    set('[data-date]', new Date(rel.published_at).toLocaleDateString('en-GB', { day: 'numeric', month: 'long', year: 'numeric' }))
    set('[data-sha]', sha.toLowerCase())
    set('[data-bytes]', exe.size.toLocaleString('en-US'))
    set('[data-check]', `(Get-FileHash "$env:USERPROFILE\\Downloads\\${exe.name}").Hash -eq "${sha.toLowerCase()}"`)
  })
  .catch(() => {})

document.querySelector('[data-copy]').addEventListener('click', (e) => {
  const btn = e.currentTarget
  navigator.clipboard.writeText(document.querySelector('[data-check]').textContent.trim()).then(
    () => (btn.textContent = 'Copied'),
    () => (btn.textContent = 'Select the text to copy'),
  )
})

