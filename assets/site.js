// Clips always autoplay without player controls (owner's choice); a blocked autoplay leaves the poster.
// Example clips play only while on screen.
const seen = new IntersectionObserver((entries) =>
  entries.forEach((en) => (en.isIntersecting ? en.target.play().catch(() => {}) : en.target.pause())),
)
document.querySelectorAll('[data-clip]').forEach((v) => seen.observe(v))

// Clips generated with Negi on the same PC; each visit shows one of them at random in the hero.
// `off: true` takes a clip out of rotation; its files stay in assets/.
const CLIPS = [
  { name: 'fox-loop', label: 'A red fox sitting in falling snow in a pine forest', time: '5 min 17 s' },
  { name: 'anime-loop', label: 'An anime girl with long turquoise hair and cherry blossom petals in the wind at sunset', time: '4 min 39 s' },
  { name: 'catgirl-loop', label: 'An anime cat girl with silver hair watching the rain from a window at night', time: '4 min 57 s' },
]
const on = CLIPS.filter((c) => !c.off)
const clip = on[Math.floor(Math.random() * on.length)]
const video = document.querySelector('[data-hero]')
if (!video.src.endsWith(`${clip.name}.mp4`)) {
  video.poster = `assets/${clip.name}.webp`
  video.src = `assets/${clip.name}.mp4`
  video.setAttribute('aria-label', `${clip.label}, generated by Negi`)
  document.querySelector('[data-hero-caption]').textContent =
    `in ${clip.time} on a GeForce RTX 3060 Ti (Wan 2.1 1.3B, 832 × 480, ${clip.how ?? '49 frames, looped with a crossfade'})`
}

// The one orchestrated moment: the clip resolves from the mark's halftone dots into footage.
// With reduced motion the clip still plays, just without the dot effect.
if (matchMedia('(prefers-reduced-motion: reduce)').matches) {
  video.play().catch(() => {})
} else {
  const box = video.parentElement
  const canvas = document.createElement('canvas')
  canvas.setAttribute('aria-hidden', 'true')
  box.append(canvas)
  const ctx = canvas.getContext('2d')
  const sample = document.createElement('canvas').getContext('2d', { willReadFrequently: true })
  const clay = getComputedStyle(document.documentElement).getPropertyValue('--clay').trim()
  const start = () => {
    const w = (canvas.width = Math.round(box.clientWidth * devicePixelRatio))
    const h = (canvas.height = Math.round(box.clientHeight * devicePixelRatio))
    // dots cover the picture as object-fit: contain places it, so they dissolve onto the footage
    const s = Math.min(w / video.videoWidth, h / video.videoHeight)
    const pw = video.videoWidth * s
    const ph = video.videoHeight * s
    const ox = (w - pw) / 2
    const oy = (h - ph) / 2
    const t0 = performance.now()
    const ms = 1700
    const frame = (now) => {
      const p = Math.min(1, (now - t0) / ms)
      const cols = Math.round(18 + 70 * p * p) // the grid gets finer as the picture resolves
      const cell = pw / cols
      const rows = Math.ceil(ph / cell)
      sample.canvas.width = cols
      sample.canvas.height = rows
      sample.drawImage(video, 0, 0, cols, rows)
      const px = sample.getImageData(0, 0, cols, rows).data
      ctx.fillStyle = '#000'
      ctx.fillRect(0, 0, w, h)
      ctx.fillStyle = clay
      for (let y = 0; y < rows; y++)
        for (let x = 0; x < cols; x++) {
          const i = (y * cols + x) * 4
          const lum = (0.2126 * px[i] + 0.7152 * px[i + 1] + 0.0722 * px[i + 2]) / 255
          const r = (cell / 2) * Math.sqrt(lum) * 0.95
          if (r < 0.4) continue
          ctx.beginPath()
          ctx.arc(ox + x * cell + cell / 2, oy + y * cell + cell / 2, r, 0, Math.PI * 2)
          ctx.fill()
        }
      canvas.style.opacity = String(p < 0.6 ? 1 : 1 - (p - 0.6) / 0.4)
      if (p < 1) requestAnimationFrame(frame)
      else canvas.remove()
    }
    requestAnimationFrame(frame)
  }
  video.play().then(start, () => canvas.remove())
}
